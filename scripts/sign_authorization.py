"""Sign a stage authorization for the REA gate.

The Ed25519 signature is computed over the canonical JSON encoding of every
top-level field except ``signature`` and is written to an explicit output file.
The shipped ``authorization.json`` is never modified, private keys are never
embedded, and no key material is generated by this tool.
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import sys
from pathlib import Path
from typing import Any

from cryptography.exceptions import UnsupportedAlgorithm
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

_SHIPPED_AUTH = (Path(__file__).resolve().parent.parent / "authorization.json").resolve()
_KEY_ENV = "ASTRA_REA_SIGNING_KEY"


class SigningError(Exception):
    """Raised when an authorization cannot be signed safely."""


def _load_private_key(raw_path: str) -> Ed25519PrivateKey:
    path = Path(raw_path)
    if not path.is_file():
        raise SigningError(f"private key file not found: {path}")
    try:
        key = serialization.load_pem_private_key(path.read_bytes(), password=None)
    except (TypeError, ValueError, UnsupportedAlgorithm) as exc:
        raise SigningError(f"invalid private key format: {type(exc).__name__}: {exc}") from exc
    if not isinstance(key, Ed25519PrivateKey):
        raise SigningError("private key is not an Ed25519 key")
    return key


def _load_auth(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise SigningError(f"authorization file not found: {path}")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise SigningError(
            f"authorization file is not valid JSON: {type(exc).__name__}: {exc}"
        ) from exc
    if not isinstance(data, dict):
        raise SigningError("authorization root must be a JSON object")
    return data


def _require_approved(auth: dict[str, Any]) -> None:
    if auth.get("artifact_status") != "APPROVED":
        raise SigningError("artifact_status must be APPROVED before signing")
    block = auth.get("authorization")
    if not isinstance(block, dict) or block.get("approval_decision") != "APPROVED":
        raise SigningError("authorization.approval_decision must be APPROVED before signing")


def _canonical_payload(auth: dict[str, Any]) -> bytes:
    payload = {k: v for k, v in auth.items() if k != "signature"}
    return json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Sign a stage authorization with Ed25519 for the REA gate."
    )
    parser.add_argument("--input", required=True, help="Input authorization JSON file")
    parser.add_argument(
        "--output", required=True, help="Output file for the signed authorization"
    )
    parser.add_argument(
        "--private-key",
        default=os.environ.get(_KEY_ENV),
        help=f"PEM Ed25519 private key (or set {_KEY_ENV})",
    )
    parser.add_argument(
        "--key-id", required=True, help="key_id bound to an active trusted-key registry entry"
    )
    args = parser.parse_args(argv)

    try:
        if not args.private_key or not args.private_key.strip():
            raise SigningError(
                "a private key is required (--private-key or " f"{_KEY_ENV})"
            )
        if not args.key_id.strip():
            raise SigningError("key_id must be a non-empty string")

        input_path = Path(args.input)
        output_path = Path(args.output)
        if output_path.resolve() == _SHIPPED_AUTH:
            raise SigningError("refusing to overwrite the shipped authorization.json")
        if input_path.resolve() == output_path.resolve():
            raise SigningError("input and output paths must differ")

        key = _load_private_key(args.private_key)
        auth = _load_auth(input_path)
        _require_approved(auth)

        signature = base64.b64encode(key.sign(_canonical_payload(auth))).decode("ascii")
        signed = dict(auth)
        signed["signature"] = {"key_id": args.key_id, "signature_base64": signature}

        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(json.dumps(signed, indent=2) + "\n", encoding="utf-8")
    except (SigningError, OSError) as exc:
        print(f"SIGNING FAILED: {exc}", file=sys.stderr)
        return 1

    print(f"Signed authorization written to: {output_path}")
    print(f"key_id: {args.key_id}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
